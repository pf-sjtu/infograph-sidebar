import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)));
const prod = process.argv[2] === "production";

/**
 * Production builds always auto-bump src/build-info.json (vYYYYMMDD.bN).
 * Dev watch does not bump (avoid spam on every file save).
 * Skip with: INFOGRAPH_SKIP_BUMP=1
 */
function autoBumpBuildInfo() {
	if (process.env.INFOGRAPH_SKIP_BUMP === "1") {
		console.log("[build] skip version bump (INFOGRAPH_SKIP_BUMP=1)");
		return;
	}
	const r = spawnSync(process.execPath, [join(root, "scripts", "bump-build.mjs")], {
		cwd: root,
		encoding: "utf8",
		stdio: ["ignore", "pipe", "pipe"],
	});
	if (r.stdout) process.stdout.write(r.stdout);
	if (r.stderr) process.stderr.write(r.stderr);
	if (r.status !== 0) {
		console.error("[build] bump-build.mjs failed");
		process.exit(r.status || 1);
	}
}

function readVersionLabel() {
	try {
		const info = JSON.parse(readFileSync(join(root, "src", "build-info.json"), "utf8"));
		return `v${info.date}.b${info.build}`;
	} catch {
		return "vunknown";
	}
}

if (prod) {
	autoBumpBuildInfo();
}

const versionLabel = readVersionLabel();
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Infograph Sidebar ${versionLabel}
*/
`;

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	console.log(`[build] production complete · ${versionLabel}`);
	process.exit(0);
} else {
	console.log(`[build] watch mode · ${versionLabel} (no auto-bump)`);
	await context.watch();
}
